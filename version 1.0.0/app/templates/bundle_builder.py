import os
import re
import json
import zipfile
import shutil
from typing import Dict, List, Any, Optional

from .typst_generator import generate_typst_manuscript, compile_typst_to_pdf
from .latex_generator import generate_latex_manuscript
from .passport_generator import generate_reproducibility_passport

def sanitize_filename(name: str) -> str:
    clean = re.sub(r'[^a-zA-Z0-9_\-]', '_', str(name))
    return clean[:55].strip('_')

def build_export_bundle(
    summary: Dict[str, Any],
    run_dir: str,
    dataset_name: str,
    zip_path: Optional[str] = None
) -> str:
    """
    Assembles a comprehensive scientific replication package containing:
    - Typst 0.15 manuscripts (main.typ, main_ieee.typ, main_nature.typ)
    - Compiled 300 DPI PDF (Research_Manuscript_Typst_v1.0.0.pdf)
    - Overleaf-compatible LaTeX manuscript (main.tex)
    - Cryptographic Reproducibility Passport (Reproducibility_Passport.md)
    - Empirical Results Chapter Draft (Manuscript_Draft.md)
    - Bitwise Calculation Ledger (calculation_ledger.json)
    - Full metadata (dataset_summary.json)
    - Figures (300 DPI distribution charts and correlation heatmaps)
    - Frequency tables (CSV tables)
    - Replication documentation (README_REPLICATION.md)
    """
    os.makedirs(run_dir, exist_ok=True)
    clean_ds_name = sanitize_filename(dataset_name)

    # 1. Ensure all manuscript sources and passport are generated
    generate_typst_manuscript(summary, run_dir, dataset_name, layout_style="ieee")
    generate_latex_manuscript(summary, run_dir, dataset_name)
    generate_reproducibility_passport(summary, run_dir, dataset_name)

    # 2. Compile Typst PDF if not already compiled or needs refresh
    typst_pdf = os.path.join(run_dir, "Research_Manuscript_Typst_v1.0.0.pdf")
    if not os.path.exists(typst_pdf):
        compile_typst_to_pdf(run_dir, "main.typ", "Research_Manuscript_Typst_v1.0.0.pdf")

    # Also compile Nature variant if possible
    nature_pdf = os.path.join(run_dir, "Research_Manuscript_Nature.pdf")
    if not os.path.exists(nature_pdf):
        compile_typst_to_pdf(run_dir, "main_nature.typ", "Research_Manuscript_Nature.pdf")

    # 3. Write Manuscript Draft MD if draft_text is in summary
    draft_path = os.path.join(run_dir, "Manuscript_Draft.md")
    draft_text = summary.get("draft_text", "")
    if not draft_text:
        draft_text = f"# Section 4: Empirical Results and Quantitative Analytics\n\nDerived from {dataset_name} (SHA-256: {summary.get('data_hash_sha256', '')[:16]}...).\n"
    with open(draft_path, "w", encoding="utf-8") as f:
        f.write(draft_text)

    # 4. Write Calculation Ledger JSON
    ledger_path = os.path.join(run_dir, "calculation_ledger.json")
    ledger_data = summary.get("ledger") or summary.get("inferential") or []
    with open(ledger_path, "w", encoding="utf-8") as f:
        json.dump(ledger_data, f, indent=2)

    # 5. Write dataset_summary.json
    summary_path = os.path.join(run_dir, "dataset_summary.json")
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    # 6. Write README_REPLICATION.md
    readme_path = os.path.join(run_dir, "README_REPLICATION.md")
    readme_content = f"""# OmniScholar Research Replication Bundle
**Dataset:** `{dataset_name}`  
**Dataset SHA-256 Checksum:** `{summary.get('data_hash_sha256', 'UNKNOWN')}`  
**Generated by:** Project OmniScholar AI Studio v1.0.0  
**Architect:** Ishwor Prasad Dhungana

## 📁 Package Contents

1. **`Research_Manuscript_Typst_v1.0.0.pdf`**: Publication-grade compiled PDF generated deterministically via Typst 0.15.1.
2. **`main.typ`**: Automated Typst 0.15 manuscript (IEEE layout default).
3. **`main_ieee.typ`**: IEEE 2-column layout template.
4. **`main_nature.typ`**: Nature/Science single-column layout template.
5. **`main.tex`**: Seamless Overleaf-compatible LaTeX source with standard TeX Live booktabs tables and embedded figures.
6. **`Reproducibility_Passport.md`**: Cryptographic audit certificate, system environment specs, and exact mathematical formula traces.
7. **`Manuscript_Draft.md`**: Academic IMRaD Section 4 Results narrative draft.
8. **`dataset_summary.json`**: Complete structured statistical summary.
9. **`calculation_ledger.json`**: Auditable bitwise calculation traces.
10. **`figures/`**: Publication 300 DPI distribution charts and correlation heatmaps.
11. **`frequency_tables/`**: Raw CSV distribution frequency tables.

## 🚀 How to Replicate

### Option A: Local Typst Compilation (Recommended)
```bash
typst compile main.typ
# Or compile Nature format:
typst compile main_nature.typ
```

### Option B: Seamless Overleaf Compilation
1. Zip this entire directory or use the pre-built `.zip` bundle.
2. Go to [Overleaf](https://www.overleaf.com), click **New Project** -> **Upload Project**.
3. Upload the `.zip` file.
4. Click **Recompile** in Overleaf (uses standard pdfLaTeX/XeLaTeX engine with zero package errors).

### Option C: Deterministic Python Verification
Inspect `Reproducibility_Passport.md` and `calculation_ledger.json` to verify each statistical test against raw data vectors with zero ghostwriting hallucination.
"""
    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(readme_content)

    # 7. Build Zip Archive
    if zip_path is None:
        runs_dir = os.path.dirname(os.path.abspath(run_dir))
        zip_filename = f"OmniScholar_Research_Package_{clean_ds_name}.zip"
        zip_path = os.path.join(runs_dir, zip_filename)

    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zipf:
        # Walk run directory and add relevant files
        for root, dirs, files in os.walk(run_dir):
            for file in files:
                # Skip temporary zip files
                if file.endswith(".zip"):
                    continue
                abs_path = os.path.join(root, file)
                rel_path = os.path.relpath(abs_path, run_dir)
                zipf.write(abs_path, arcname=rel_path)

    print(f"[OmniScholar Engine] Export bundle created: {zip_path} ({os.path.getsize(zip_path)} bytes)")
    return zip_path
